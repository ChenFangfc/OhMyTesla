#!/usr/bin/env python3
"""Turn a `pip install --dry-run --report` JSON into a hash-pinned requirements lock.

    pylock.py <report.json> <requirements.txt> <out.lock>

The lock records name==version plus the SHA-256 of the exact file pip chose
for this platform (macOS arm64, CPython 3.12), so `pip install
--require-hashes -r out.lock` reproduces the environment byte for byte.
"""

import datetime
import hashlib
import json
import sys


def main() -> int:
    report_path, req_path, out_path = sys.argv[1:4]
    with open(report_path, encoding="utf-8") as f:
        report = json.load(f)
    with open(req_path, "rb") as f:
        req_sha = hashlib.sha256(f.read()).hexdigest()

    minor = f"{sys.version_info.major}.{sys.version_info.minor}"
    lines = [
        "# Hash-pinned Python dependencies of services/hub for the macOS app",
        f"# cpython={minor} platform=macosx-arm64. Generated by `build.sh --relock`; do not edit.",
        f"# Resolved {datetime.date.today().isoformat()} from services/hub/requirements.txt "
        f"(sha256 {req_sha}).",
        "",
    ]
    items = sorted(report["install"], key=lambda i: i["metadata"]["name"].lower())
    for item in items:
        name = item["metadata"]["name"]
        version = item["metadata"]["version"]
        info = item["download_info"]
        archive = info.get("archive_info", {})
        sha = (archive.get("hashes") or {}).get("sha256")
        if not sha and archive.get("hash", "").startswith("sha256="):
            sha = archive["hash"].split("=", 1)[1]
        if not sha:
            print(f"no sha256 for {name} {version} ({info.get('url')})", file=sys.stderr)
            return 1
        lines.append(f"# {info.get('url', '').rsplit('/', 1)[-1]}")
        lines.append(f"{name}=={version} --hash=sha256:{sha}")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}: {len(items)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
