"""取证包导出：一次打一个 ZIP，把事故需要的全部材料装齐。

为什么值得单独做：出事之后要交给保险或警方的，从来不只是一段视频。
对方会问"什么时候、在哪、多快、谁在开"，而这些答案分散在四个地方 ——
原始片段在 U 盘、时间在文件名、速度在 SEI、位置和电量在 TeslaMate。
用户在最慌乱的时候要自己拼这些，拼错一处整份材料的可信度就没了。

包里有什么，以及为什么：
  raw/                原始片段，逐字节复制。**不重新编码** —— 转码过的视频
                      在取证上价值大打折扣，对方有理由质疑画面被处理过。
  event.json          特斯拉自己写的事件元数据（触发原因、估算经纬度、城市）
  telemetry.csv       逐帧 SEI（车速、方向盘、踏板、挡位、自驾状态）
  drive.csv           同时段的 TeslaMate 记录（SOC、功率、海拔、内外温度）
  manifest.json       清单 + 每个文件的 SHA-256 + 时钟偏移
  README.txt          给不懂技术的人看的一页纸说明

**流式输出**：ZIP 边打边发，内存里任何时候只有一两个 1 MB 的块。以前整包在
内存里拼（还要再复制一次），10 分钟的 HW4 事件约 2 GB 片段，峰值内存是片段
总量的 2.4 倍 —— 4-8 GB 的树莓派/NAS 上 uvicorn 直接被 OOM 杀掉，门户、
告警、监视器一起下线。校验和在读文件时顺手按块算。

manifest 里的校验和不是装样子：交出去之后对方可以验证文件没被改过，
而"我们自己算的时钟偏移是多少秒"这种事必须写在纸面上 ——
片段文件名用的是车机本地时钟，和 TeslaMate 的 UTC 之间有偏移，
不声明的话两份材料的时间对不上，反而成了破绽。
"""

import asyncio
import contextlib
import csv
import hashlib
import io
import json
import logging
import queue
import threading
import zipfile
from collections.abc import AsyncIterator
from datetime import datetime, timedelta, timezone
from pathlib import Path

log = logging.getLogger(__name__)

CHUNK = 1 << 20

README = """OhmyTesla 取证包 / Evidence package
=====================================

事件 / Event: {event_id}
类型 / Type: {event_type}
触发时刻 / Triggered: {when} (车机本地时间 / vehicle local time, {tz})
地点 / Location: {place}

这个压缩包由车主自己的 OhmyTesla 实例生成，所有处理都在本机完成。
This archive was generated by the vehicle owner's own OhmyTesla instance; all
processing happened locally.

目录 / Contents
---------------
raw/            行车记录仪原始片段，逐字节复制，未经任何重新编码。
                Original dashcam clips, copied byte for byte, never re-encoded.
event.json      车辆自己写入的事件元数据（触发原因、估算坐标）。
                Event metadata written by the vehicle (trigger reason, estimated position).
telemetry.csv   逐帧车辆遥测，从视频码流内嵌的 SEI 数据解出：
                车速、方向盘转角、油门/刹车、挡位、自动驾驶状态。
                Per-frame vehicle telemetry decoded from the SEI data embedded in the
                video: speed, steering angle, pedal/brake, gear, Autopilot state.
drive.csv       同一时段的行车记录（电量、功率、海拔、内外温度、坐标），来自 TeslaMate。
                Drive log for the same period (battery, power, elevation, temperatures,
                position), from TeslaMate.
manifest.json   文件清单与每个文件的 SHA-256 校验和。
                File list with a SHA-256 checksum for every file.

时钟说明 / Clock
----------------
片段文件名和 telemetry.csv 的 segment_start 列使用车辆本机时钟；drive.csv 使用 UTC。
Clip file names and the segment_start column of telemetry.csv use the vehicle's own
clock; drive.csv uses UTC.

本包采用的时钟偏移 / Clock offset used: {offset} 秒 / seconds
  车机时钟 + 偏移 = 真实时间（即 车机时钟 = 真实时间 − 偏移）。
  vehicle clock + offset = true time (i.e. vehicle clock = true time − offset).
{offset_source}
telemetry.csv 的 timestamp_utc 列已经按这个偏移换算成真实 UTC 时间，可以直接与
drive.csv 的 timestamp_utc 列对照；segment_start / t 两列保留车机原始时间，未做修改。
The timestamp_utc column of telemetry.csv already applies this offset and is directly
comparable with the timestamp_utc column of drive.csv; the segment_start / t columns
keep the vehicle's original clock, unmodified.

校验 / Verification
-------------------
manifest.json 里每个文件都附了 SHA-256。任何一位改动都会导致校验失败。
manifest.json lists a SHA-256 for every file; changing a single bit breaks the check.
在 macOS / Linux 上核对 / to verify on macOS or Linux:  shasum -a 256 <file>
在 Windows 上 / on Windows:  certutil -hashfile <file> SHA256
"""


class _Aborted(Exception):
    """下载方断开了：生产线程尽快收手。"""


class _Pipe(io.RawIOBase):
    """zipfile 的输出端。不可 seek，所以 zipfile 会用 data descriptor 流式写。

    写满一个块就交给队列；队列满了（下载方读得慢）就等，形成背压 ——
    这样内存里最多只有 maxsize 个块。
    """

    def __init__(self, q: queue.Queue, cancelled: threading.Event) -> None:
        super().__init__()
        self._q = q
        self._buf = bytearray()
        self._cancelled = cancelled

    def writable(self) -> bool:
        return True

    def seekable(self) -> bool:
        return False

    def write(self, b) -> int:
        if self._cancelled.is_set():
            raise _Aborted
        self._buf += b
        if len(self._buf) >= CHUNK:
            self._push()
        return len(b)

    def _push(self) -> None:
        data = bytes(self._buf)
        self._buf.clear()
        while True:
            try:
                self._q.put(data, timeout=0.5)
                return
            except queue.Full:
                if self._cancelled.is_set():
                    raise _Aborted from None

    def flush(self) -> None:
        if self._buf:
            self._push()


_EOF = object()


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while chunk := f.read(CHUNK):
            h.update(chunk)
    return h.hexdigest()


def _write_file(z: zipfile.ZipFile, src: Path, arc: str) -> tuple[str, int]:
    """把一个文件流式写进 ZIP，同时算 SHA-256。返回 (sha256, 字节数)。"""
    st = src.stat()
    # ZIP 的时间字段是无时区的本地时间，范围 1980-2107。车机写的 mtime 经常离谱，夹住
    stamp = datetime.fromtimestamp(st.st_mtime).timetuple()[:6]  # noqa: DTZ006 - 见上
    stamp = max((1980, 1, 1, 0, 0, 0), min(stamp, (2107, 12, 31, 23, 59, 58)))
    zi = zipfile.ZipInfo(arc, date_time=stamp)
    zi.compress_type = zipfile.ZIP_DEFLATED
    zi.file_size = st.st_size          # 预先告知大小，zipfile 据此决定要不要 zip64
    h = hashlib.sha256()
    n = 0
    with src.open("rb") as f, z.open(zi, "w") as out:
        while chunk := f.read(CHUNK):
            h.update(chunk)
            out.write(chunk)
            n += len(chunk)
    return h.hexdigest(), n


def _write_blob(z: zipfile.ZipFile, arc: str, blob: bytes) -> dict:
    z.writestr(arc, blob)
    return {"sha256": hashlib.sha256(blob).hexdigest(), "bytes": len(blob)}


async def build(event_id: str, car_id: int | None = None) -> tuple[AsyncIterator[bytes], str]:
    """准备好需要查库的部分，返回 (ZIP 字节流, 建议的文件名)。

    查库（时钟偏移、TeslaMate 行车记录）在协程里做完；读文件、算校验和、压缩
    在独立线程里边做边往外送。
    """
    from .. import db
    from . import telemetry
    from .scanner import _teslacam_base, fill_durations, scanner

    base = _teslacam_base()
    if base is None:
        raise ValueError("TeslaCam directory not found")
    ev = await scanner.aget(event_id)
    if ev is None:
        raise ValueError(f"event not found: {event_id}")

    if car_id is None:
        try:
            row = await db.fetchrow("SELECT id FROM cars ORDER BY id LIMIT 1")
            car_id = row["id"] if row else 1
        except db.DbUnavailable:
            car_id = 1

    offset = await telemetry.clock_offset(car_id)
    await fill_durations(ev, base)

    # 同时段的行车记录：查询窗口两端都要加上时钟偏移（文件名时间 + 偏移 = TeslaMate 时间）。
    # 以前起点减偏移、终点不加，偏移超过 60 秒时 drive.csv 开头那一段直接没了。
    drive_rows: list[dict] = []
    drive_err = None
    try:
        last = ev.segments[-1]
        start_utc = telemetry.local_naive_to_utc(ev.segments[0].start) + timedelta(seconds=offset)
        end_utc = (telemetry.local_naive_to_utc(last.start)
                   + timedelta(seconds=(last.duration or 60.0) + offset))
        drive_rows = await telemetry.fetch_positions(car_id, start_utc, end_utc, pad_s=60)
    except Exception as e:
        log.warning("evidence: could not attach drive data", exc_info=True)
        drive_err = str(e)[:200]

    stamp = ev.timestamp.strftime("%Y%m%d-%H%M%S")
    name = f"ohmytesla-evidence-{ev.type}-{stamp}.zip"
    return _stream(ev, base, offset, car_id, drive_rows, drive_err), name


async def _stream(ev, base: Path, offset: float, car_id, drive_rows: list,
                  drive_err: str | None) -> AsyncIterator[bytes]:
    q: queue.Queue = queue.Queue(maxsize=4)
    cancelled = threading.Event()

    def produce() -> None:
        try:
            _pack(_Pipe(q, cancelled), ev, base, offset, car_id, drive_rows, drive_err)
        except _Aborted:
            log.info("evidence download for %s aborted by the client", ev.id)
        except Exception as e:
            log.exception("evidence package for %s failed", ev.id)
            with contextlib.suppress(queue.Full):
                q.put(e, timeout=5)
        finally:
            while True:
                try:
                    q.put(_EOF, timeout=0.5)
                    break
                except queue.Full:
                    if cancelled.is_set():
                        with contextlib.suppress(queue.Empty):
                            q.get_nowait()

    worker = threading.Thread(target=produce, name="evidence-zip", daemon=True)
    worker.start()
    try:
        while True:
            item = await asyncio.to_thread(q.get)
            if item is _EOF:
                break
            if isinstance(item, Exception):
                # 已经发出去一部分了，没法再改状态码；中断连接，客户端拿到的是不完整的
                # ZIP（解压会报错），不会被误当成完整的取证包
                raise item
            yield item
    finally:
        cancelled.set()
        with contextlib.suppress(queue.Empty):
            while True:
                q.get_nowait()


def _pack(sink: _Pipe, ev, base: Path, offset: float, car_id,
          drive_rows: list, drive_err: str | None) -> None:
    """纯同步：读文件、算校验和、压缩，边做边写进 sink。由 _stream 在线程里调用。"""
    from . import probe, sei
    from .localtime import describe, local_naive_to_utc

    tzinfo = describe()
    manifest: dict = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "event_id": ev.id,
        "event_type": ev.type,
        "event_timestamp_local": ev.timestamp.isoformat(),
        "vehicle_time_zone": tzinfo["name"],
        "car_id": car_id,
        "clock_offset_seconds": offset,
        "clock_offset_meaning": "vehicle clock + offset = true time (TeslaMate/UTC)",
        "files": {},
        # 把口径写进包里。收件方不该去猜我们的 "speed" 是 km/h 还是 mph。
        "units": {"speed": "km/h", "distance": "km", "temperature": "C", "power": "kW"},
        "source": "OhmyTesla — self-hosted, processed locally",
    }

    # ZIP_DEFLATED + level 1：mp4 本来就压过了，压不小；但"流式 + DEFLATE + data
    # descriptor"是兼容性最好的组合（STORED + data descriptor 有的解压库不认）
    with zipfile.ZipFile(sink, "w", zipfile.ZIP_DEFLATED, compresslevel=1, allowZip64=True) as z:
        # ── 原始片段
        unreadable = []
        for seg in ev.segments:
            for cam, rel in seg.cameras.items():
                src = base / rel
                if not src.is_file():
                    continue
                arc = f"raw/{Path(rel).name}"
                digest, n = _write_file(z, src, arc)
                info = probe.probe_sync(src)
                entry = {"sha256": digest, "bytes": n, "camera": cam,
                         "segment_start_local": seg.start.isoformat(),
                         "duration_s": info.get("duration")}
                if not info.get("ok"):
                    # 截断/加密的片段照样原样放进来（它就是证据本身），但标明读不出来
                    entry["readable"] = False
                    entry["note"] = info.get("reason") or "unreadable"
                    unreadable.append(arc)
                manifest["files"][arc] = entry
        if unreadable:
            manifest["unreadable_clips_note"] = (
                f"{len(unreadable)} clip(s) could not be decoded (truncated or encrypted); "
                "they are included unmodified.")

        # ── 车辆自己写的事件元数据
        meta = {"reason": ev.reason, "city": ev.city,
                "est_lat": ev.est_lat, "est_lon": ev.est_lon,
                "timestamp": ev.timestamp.isoformat(), "type": ev.type}
        manifest["files"]["event.json"] = _write_blob(
            z, "event.json", json.dumps(meta, ensure_ascii=False, indent=2).encode())

        # ── 逐帧 SEI。timestamp_utc = 文件名时间 + t + 偏移，和 drive.csv 同一条时间轴
        rows = []
        for seg in ev.segments:
            picked = next((seg.cameras[c] for c in ("front", "F", "main") if c in seg.cameras),
                          next(iter(seg.cameras.values()), None))
            if not picked:
                continue
            seg_utc = local_naive_to_utc(seg.start).timestamp() + offset
            for smp in sei.extract(base / picked, step=0.2, strict=True):
                rows.append({
                    "segment_start": seg.start.isoformat(),
                    "segment_file": Path(picked).name,
                    "timestamp_utc": datetime.fromtimestamp(
                        seg_utc + smp["t"], timezone.utc).isoformat(timespec="milliseconds"),
                    **smp,
                })
        if rows:
            sio = io.StringIO()
            w = csv.DictWriter(sio, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
            manifest["files"]["telemetry.csv"] = {
                **_write_blob(z, "telemetry.csv", sio.getvalue().encode()), "samples": len(rows)}
        else:
            # 没有就明说，别让收件方以为是我们漏了
            manifest["telemetry_note"] = (
                "No SEI telemetry: parked Sentry clips never carry it, and neither do "
                "driving clips from firmware older than 2025.44.25.")

        # ── 同时段的 TeslaMate 记录（数据已由 build() 在协程里取好）
        if drive_rows:
            out_rows = [{"timestamp_utc": datetime.fromtimestamp(r["date"], timezone.utc).isoformat(),
                         **r} for r in drive_rows]
            sio = io.StringIO()
            w = csv.DictWriter(sio, fieldnames=list(out_rows[0].keys()))
            w.writeheader()
            w.writerows(out_rows)
            manifest["files"]["drive.csv"] = {
                **_write_blob(z, "drive.csv", sio.getvalue().encode()), "samples": len(drive_rows)}
        elif drive_err:
            manifest["drive_note"] = f"TeslaMate data was unavailable: {drive_err}"

        # ── 说明书
        readme = README.format(
            event_id=ev.id, event_type=ev.type,
            when=ev.timestamp.isoformat(sep=" "), tz=tzinfo["name"],
            place=ev.city or (f"{ev.est_lat}, {ev.est_lon}" if ev.est_lat else "unknown"),
            offset=f"{offset:+.1f}",
            offset_source=("  （由自动校准或手动设置得到 / from automatic or manual calibration）"
                           if offset else
                           "  （未校准，按 0 处理 / not calibrated, treated as 0）"),
        ).encode()
        manifest["files"]["README.txt"] = _write_blob(z, "README.txt", readme)

        # manifest 最后写：它要包含前面所有文件的校验和，自己不参与校验
        z.writestr("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))
    sink.flush()
